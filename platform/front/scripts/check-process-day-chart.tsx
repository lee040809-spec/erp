import assert from 'node:assert/strict';

import { renderToStaticMarkup } from 'react-dom/server';
import ProcessGanttChart from '../src/components/ProcessGanttChart';
import { processDate } from '../src/utils/processDates';
import { invalidOrderProcessDates } from '../src/components/OrderProcessDates';
import { GANTT_DAY, ganttDay, processScheduleRisk, lastProcessDeliveryRisk, timelineExtent } from '../src/utils/ganttSchedule';

assert.equal(processDate('2026-09-01T17:30:00Z'), '2026-09-02');
assert.equal(processDate('2026-09-01'), '2026-09-01');
const process = {id:1,name:'铣削',is_outsourced:false,outsourcing_fee:0,status:'completed' as const,planned_start_at:'2026-09-01',planned_end_at:'2026-09-01',actual_start_at:'2026-09-01T01:15:00Z',actual_end_at:'2026-09-01T15:45:00Z'};
assert.equal(invalidOrderProcessDates([process]), false);
assert.equal(invalidOrderProcessDates([{...process,planned_end_at:'2026-08-31'}]), true);
assert.equal(invalidOrderProcessDates([{...process,planned_end_at:''}]), true);
const html = renderToStaticMarkup(<ProcessGanttChart rows={[{itemId:1,partName:'按天图形测试',process}]}/>);
assert.match(html, /计划：2026-09-01 → 2026-09-01/);
assert.match(html, /实际：2026-09-01 → 2026-09-01/);
assert.match(html, /erp-gantt-planned[^>]+width:7\.142857142857142%/);
assert.match(html, /erp-gantt-completed[^>]+width:7\.142857142857142%/);
assert.doesNotMatch(html, /01:15|15:45|datetime-local/);
const grouped = renderToStaticMarkup(<ProcessGanttChart rows={[
  {itemId:1,partName:'同名零件',orderNumber:'ORDER-1',startDate:'2026-08-31',process},
  {itemId:2,partName:'同名零件',orderNumber:'ORDER-2',process:{...process,id:2}},
]}/>);
assert.equal(grouped.match(/class="erp-gantt-group"/g)?.length, 2);
assert.equal(grouped.match(/class="erp-gantt-part-name">同名零件/g)?.length, 2);
assert.match(grouped, /ORDER-1/);
assert.match(grouped, /ORDER-2/);
assert.match(grouped, /下单 2026-08-31/);
assert.match(grouped, /下单 未填/);
assert.match(grouped, /aria-expanded="true"/);
assert.match(grouped, /全部折叠/);
console.log('PASS: Beijing calendar dates, same-day full-width bars, daily tooltips, paired order dates and invalid ranges.');
console.log('PASS: item groups keep identical part names in different orders separate and expanded by default.');

const now = Date.parse('2026-10-07T02:00:00Z');
const longProcess = { ...process, status: 'processing' as const, planned_start_at: '2026-10-08', planned_end_at: '2026-11-06', actual_start_at: null, actual_end_at: null };
const nextProcess = { ...longProcess, id: 2, name: '表面处理', status: 'pending' as const, planned_start_at: '2026-10-16', planned_end_at: '2026-11-10' };
const longRows = [longProcess, nextProcess].map(p => ({ itemId: 3, partName: '长工序', dueDate: '2026-03-31', process: p }));
const longHtml = renderToStaticMarkup(<ProcessGanttChart rows={longRows} />);
assert.match(longHtml, /续至 2026-11-06 ›/);
assert.match(longHtml, /续至 2026-11-10 ›/);
assert.match(longHtml, /2026-10-08 → 2026-11-06/);
assert.match(longHtml, /交期 2026-03-31/);
assert.doesNotMatch(longHtml, /计划晚 220 天|计划晚 224 天|工序超期/);
assert.match(longHtml, /末道计划晚于客户交期 224 天/);
assert.match(longHtml, /erp-gantt-delivery-row/);
assert.match(longHtml, /暂无实际送货记录/);
assert.match(longHtml, /查看全程/);
const range = timelineExtent(longRows, now);
assert.ok(range.start <= ganttDay('2026-03-31'));
assert.ok(range.start + range.days * GANTT_DAY > ganttDay('2026-11-10'));
assert.equal(processScheduleRisk(longProcess, now), '');
assert.equal(processScheduleRisk(nextProcess, now), '');
assert.equal(processScheduleRisk({ ...longProcess, actual_end_at: '2026-11-09' }, now), '完工晚于计划 3 天');
assert.equal(processScheduleRisk({ ...longProcess, actual_end_at: '2026-11-06' }, now), '');
assert.equal(processScheduleRisk({ ...longProcess, status: 'completed' }, now), '实际日期待补录');
assert.equal(processScheduleRisk({ ...longProcess, planned_end_at: null }, now), '');
assert.equal(processScheduleRisk({ ...longProcess, planned_end_at: '2026-10-05' }, now), '工序超期 2 天');
assert.equal(lastProcessDeliveryRisk([longProcess, nextProcess], '2026-11-08'), '末道计划晚于客户交期 2 天');
assert.equal(lastProcessDeliveryRisk([longProcess, nextProcess], '2026-11-10'), '');
const shipping = { last_date:'2026-12-15', delivered_quantity:7, dated_quantity:5, undated_quantity:2, batches:3 };
const partOnly = { itemId:4, partName:'仅送货节点', dueDate:'2026-12-14', quantity:10, delivery:shipping };
const deliveryHtml = renderToStaticMarkup(<ProcessGanttChart rows={[]} parts={[partOnly]}/>);
assert.match(deliveryHtml, /部分交货/);
assert.match(deliveryHtml, /最近实际送货 2026-12-15/);
assert.match(deliveryHtml, /2 件日期未知/);
assert.match(deliveryHtml, /最近送货晚于交期 1 天/);
assert.doesNotMatch(deliveryHtml, /暂无零件/);
const deliveryRange = timelineExtent([partOnly], now);
assert.ok(deliveryRange.start + deliveryRange.days * GANTT_DAY > ganttDay(shipping.last_date));
const oldDelivery = renderToStaticMarkup(<ProcessGanttChart rows={[]} parts={[{...partOnly, delivery:{...shipping,last_date:'',dated_quantity:0,undated_quantity:7}}]}/>);
assert.match(oldDelivery, /历史送货日期待补录/);
assert.doesNotMatch(oldDelivery, /最近实际送货/);
console.log('PASS: process deadlines are independent of customer due dates; future stages are not labeled 220/224 days overdue; delivery comparison states its baseline.');
console.log('PASS: shipping milestones, partial and undated historical deliveries, full-year dates and full ranges including recorded deliveries.');
